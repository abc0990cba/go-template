#!/usr/bin/env bash
# `make vps-local` — ONE command local rehearsal of the whole deploy flow.
#
# Creates/reuses an OrbStack Ubuntu machine ("local VPS"), runs the SAME
# Ansible playbooks as production against it (base → docker → nomad → stack),
# builds the app image from your current working tree inside the machine, then
# verifies everything with a PASS/FAIL table.
#
#   first run ≈ 10–20 min (machine create + pinned installs + image build)
#   re-runs   ≈ 1–2 min  (VPS_SITE=local make vps-deploy)
#   teardown  = orb delete go-template-vps && rm -rf deploy/ansible/.vps-state
#
# See docs/deployment/vps/LOCAL-REHEARSAL.md.
set -euo pipefail
# This script always targets the local site — pin it before lib.sh derives paths.
export VPS_SITE="${VPS_SITE:-local}"
# shellcheck source=lib.sh
source "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/lib.sh"

MACHINE="${ORB_MACHINE:-go-template-vps}"
HOST="${MACHINE}.orb.local"
# OrbStack's ubuntu:24.04 image ships a default user named "developer"
# (no "ubuntu" user). Override with ORB_SSH_USER if you use another image.
SSH_USER="${ORB_SSH_USER:-developer}"
KEY="$STATE_DIR/local_key"
REPO_ROOT="$(cd "$ANSIBLE_DIR/../.." && pwd)"
INV_LOCAL="$ANSIBLE_DIR/inventories/local"

command -v orb >/dev/null 2>&1 || die "OrbStack CLI not found. Install: brew install orbstack (then open OrbStack once)"
command -v rsync >/dev/null 2>&1 || die "rsync not found (macOS ships it; check PATH)"

echo
info "Local rehearsal: deploy the entire stack to OrbStack machine '${MACHINE}'"
echo "    target: ${SSH_USER}@${HOST}   (same playbooks as production, hardening_level=light, tls internal)"

# --- phase 0: machine ----------------------------------------------------------
if orb list 2>/dev/null | awk '{print $1}' | grep -qx "$MACHINE"; then
  orb start "$MACHINE" >/dev/null 2>&1 || true
  ok "machine '$MACHINE' exists (reusing; delete with: orb delete $MACHINE)"
else
  info "Creating Ubuntu 24.04 machine (one-time, ~1 min)..."
  orb create ubuntu:24.04 "$MACHINE"
fi

# --- phase 1: ssh key + sshd -----------------------------------------------------
mkdir -p "$STATE_DIR"
umask 077
if [ ! -f "$KEY" ]; then
  ssh-keygen -t ed25519 -N "" -C "go-template-local-rehearsal" -f "$KEY" -q
  ok "generated rehearsal key $KEY"
fi
SSH_OPTS=("-i" "$KEY" "-o" "IdentitiesOnly=yes" "-o" "BatchMode=yes" "-o" "ConnectTimeout=5" "-o" "StrictHostKeyChecking=accept-new")
RSYNC_SSH="ssh -i '$KEY' -o IdentitiesOnly=yes -o BatchMode=yes -o StrictHostKeyChecking=accept-new"
if ! ssh "${SSH_OPTS[@]}" "$SSH_USER@$HOST" true 2>/dev/null; then
  info "Installing openssh-server and the rehearsal key in the machine..."
  orb -m "$MACHINE" sudo env DEBIAN_FRONTEND=noninteractive bash -c \
    'apt-get update -qq && apt-get install -y -qq openssh-server >/dev/null && (systemctl enable --now ssh >/dev/null 2>&1 || systemctl restart ssh)'
  TARGET_HOME=$(orb -m "$MACHINE" bash -c "getent passwd $SSH_USER | cut -d: -f6")
  [ -n "$TARGET_HOME" ] || die "user '$SSH_USER' not found in the machine (set ORB_SSH_USER)"
  cat "$KEY.pub" | orb -m "$MACHINE" sudo bash -c \
    "mkdir -p '$TARGET_HOME/.ssh' && chmod 700 '$TARGET_HOME/.ssh' \
     && tee -a '$TARGET_HOME/.ssh/authorized_keys' >/dev/null \
     && chmod 600 '$TARGET_HOME/.ssh/authorized_keys' \
     && chown -R '$SSH_USER' '$TARGET_HOME/.ssh'"
fi
# sshd may still be settling right after install — retry briefly.
SSH_OK=0
for _ in 1 2 3 4 5; do
  if ssh "${SSH_OPTS[@]}" "$SSH_USER@$HOST" true 2>/dev/null; then SSH_OK=1; break; fi
  sleep 3
done
[ "$SSH_OK" = 1 ] || die "SSH into the machine failed even after setup"
ok "SSH ok: $SSH_USER@$HOST"

# Local domains resolve inside the machine too (smoke check + blackbox probe).
orb -m "$MACHINE" bash -c 'grep -q "go-template.test" /etc/hosts || echo "127.0.0.1 app.go-template.test ci.go-template.test grafana.go-template.test" | sudo tee -a /etc/hosts >/dev/null'

# --- state + inventory + secrets -------------------------------------------------
cat > "$STATE_FILE" <<EOF
vps_host="${HOST}"
vps_ssh_user="${SSH_USER}"
vps_ssh_key="${KEY}"
vps_kind="orbstack"
EOF
cat > "$INV_LOCAL/hosts.yml" <<EOF
# Generated by vps-local.sh (gitignored).
all:
  children:
    vps:
      hosts:
        go-template-vps:
          ansible_host: ${HOST}
          ansible_user: ${SSH_USER}
          ansible_ssh_private_key_file: ${KEY}
EOF
# Local domains resolve inside the machine too (smoke check + blackbox probe).
orb -m "$MACHINE" bash -c 'grep -q "go-template.test" /etc/hosts || echo "127.0.0.1 app.go-template.test ci.go-template.test grafana.go-template.test" | sudo tee -a /etc/hosts >/dev/null'
SECRETS_FILE="$INV_LOCAL/group_vars/vps/secrets.yml"
VAULT_PASS="$ANSIBLE_DIR/.vault-pass"
[ -f "$VAULT_PASS" ] || { openssl rand -base64 32 > "$VAULT_PASS"; chmod 600 "$VAULT_PASS"; }
if [ -f "$SECRETS_FILE" ]; then
  # Catch a lost/rotated vault pass here with a clear message instead of a
  # cryptic decryption failure deep inside the playbook.
  ansible-vault view "$SECRETS_FILE" >/dev/null 2>&1 \
    || die "secrets.yml exists but cannot be decrypted with .vault-pass.
If this is a throwaway local rehearsal, regenerate it:
  rm '$SECRETS_FILE' && make vps-local"
fi
if [ ! -f "$SECRETS_FILE" ]; then
  info "Generating local secrets (encrypted; separate from prod)..."
  PG=$(openssl rand -hex 24); JWT=$(openssl rand -hex 32); WP=$(openssl rand -hex 24)
  GRF=$(openssl rand -base64 18 | tr -d '/+=')
  cat > "$SECRETS_FILE" <<EOF
# Generated by vps-local.sh. Encrypted at rest; local-only.
secrets:
  postgres_password: "${PG}"
  jwt_secret: "${JWT}"
  grafana_admin_password: "${GRF}"
  woodpecker_agent_secret: "${WP}"
  woodpecker_github_client_id: ""
  woodpecker_github_client_secret: ""
  telegram_bot_token: ""
  telegram_chat_id: ""
  slack_webhook_url: ""
  alerting_smtp_host: ""
  alerting_smtp_port: "587"
  alerting_smtp_from: ""
  alerting_smtp_to: ""
  alerting_smtp_username: ""
  alerting_smtp_password: ""
  app_smtp_password: ""
  app_oauth_google:   { client_id: "", client_secret: "" }
  app_oauth_github:   { client_id: "", client_secret: "" }
  app_oauth_facebook: { client_id: "", client_secret: "" }
  app_oauth_twitter:  { client_id: "", client_secret: "" }
  backup_rclone_remote: ""
  backup_rclone_config: ""
EOF
  ansible-vault encrypt "$SECRETS_FILE" >/dev/null
fi
ok "inventory + secrets ready (VPS_SITE=local)"

# --- phase 2: base system (pinned docker + nomad, no stack yet) -------------------
info "Phase 2/5: base system via the production playbook (hardening_level=light)..."
VPS_SITE=local "$ANSIBLE_DIR/scripts/run-playbook.sh" site.yml --skip-tags stack,backup,smoke

# --- phase 3: sync working tree + build the image inside the machine --------------
info "Phase 3/5: syncing your working tree and building the app image (cached after first build)..."
# Ubuntu's minimal cloud image ships without rsync.
ssh "${SSH_OPTS[@]}" "$SSH_USER@$HOST" \
  'command -v rsync >/dev/null 2>&1 || { sudo env DEBIAN_FRONTEND=noninteractive apt-get update -qq && sudo env DEBIAN_FRONTEND=noninteractive apt-get install -y -qq rsync; }'
rsync -a --delete -e "$RSYNC_SSH" \
  --exclude /.git --exclude /.zcode --exclude /.github \
  --exclude /docs --exclude /test --exclude /scripts --exclude /deploy \
  --exclude node_modules --exclude web/node_modules --exclude web/dist \
  --exclude "coverage.*" --exclude "*.dump" --exclude ".env" \
  "$REPO_ROOT/" "$SSH_USER@$HOST:src/"
TAG="$(get_var app_image_tag "$INV_LOCAL/group_vars/vps/main.yml")"
# No DATE build-arg here: a changing arg would invalidate the Go layer cache
# on every rehearsal (CI stamps the real date per tag).
ssh "${SSH_OPTS[@]}" "$SSH_USER@$HOST" "cd ~/src && sudo docker build \
  --build-arg VERSION=${TAG} --build-arg COMMIT=local \
  -t 127.0.0.1:5000/go-template:${TAG} ."
ok "image 127.0.0.1:5000/go-template:${TAG} built in the machine"

# --- phase 4: full stack ------------------------------------------------------------
info "Phase 4/5: full stack converge (same as production)..."
VPS_SITE=local "$ANSIBLE_DIR/scripts/run-playbook.sh" site.yml

# --- phase 5: verify ------------------------------------------------------------------
info "Phase 5/5: verification"
set +e
VPS_SITE=local "$ANSIBLE_DIR/scripts/vps-verify.sh"
VERIFY_RC=$?
set -e

APP_DOMAIN=$(get_var app_domain "$INV_LOCAL/group_vars/vps/main.yml")
CI_DOMAIN=$(get_var ci_domain "$INV_LOCAL/group_vars/vps/main.yml")
GRAF_DOMAIN=$(get_var grafana_domain "$INV_LOCAL/group_vars/vps/main.yml")
echo
if [ "$VERIFY_RC" -eq 0 ]; then ok "REHEARSAL COMPLETE — the whole deploy flow works end to end"; else fail "rehearsal finished WITH FAILURES — see the table above"; fi
echo
echo "Make the sites resolvable in your browser (OrbStack forwards machine ports to localhost):"
echo "  sudo tee -a /etc/hosts >/dev/null <<'EOF'
127.0.0.1 ${APP_DOMAIN} ${CI_DOMAIN} ${GRAF_DOMAIN}
EOF"
echo "Then open:  https://${APP_DOMAIN}   (accept the self-signed warning, or trust the CA once:"
echo "  orb -m ${MACHINE} sudo cat ${vps_base_dir:-/opt/go-template}/data/caddy/pki/authorities/local/root.crt \\"
echo "    > /tmp/go-template-local-root.crt && sudo security add-trusted-cert -d -r trustRoot \\"
echo "    -k /Library/Keychains/System.keychain /tmp/go-template-local-root.crt )"
echo
echo "Re-runs:   VPS_SITE=local make vps-deploy        # ~1-2 min"
echo "           VPS_SITE=local make vps-app-deploy TAG=..."
echo "           VPS_SITE=local make vps-logs S=api"
echo "Teardown:  orb delete ${MACHINE} && rm -rf deploy/ansible/.vps-state"
exit "$VERIFY_RC"
