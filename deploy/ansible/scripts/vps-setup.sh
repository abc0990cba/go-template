#!/usr/bin/env bash
# `make vps-setup` — guided first-time setup for a site (default: prod).
# Collects 6 answers, generates every secret, encrypts them with a
# locally-stored vault password, and writes the inventory. Run once per VPS.
set -euo pipefail
# shellcheck source=lib.sh
source "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/lib.sh"

info "VPS setup for site '${VPS_SITE}' (${ANSIBLE_DIR}/inventories/${VPS_SITE})"
echo
SECRETS_FILE="$ANSIBLE_DIR/inventories/$VPS_SITE/group_vars/vps/secrets.yml"
SITE_VARS="$ANSIBLE_DIR/inventories/$VPS_SITE/group_vars/vps/site.yml"
VAULT_PASS="$ANSIBLE_DIR/.vault-pass"

if [ -f "$SECRETS_FILE" ]; then
  die "secrets.yml already exists for site '$VPS_SITE'. Setup already ran.
To change domains/versions edit group_vars/vps/{main.yml,site.yml} and re-run 'make vps-deploy'.
To rotate a secret edit it with 'ansible-vault edit' (docs/vps/runbook.md)."
fi

# --- 0. Prerequisites ---------------------------------------------------------
if ! command -v ansible-playbook >/dev/null 2>&1; then
  die "ansible-playbook is not installed. Install ansible-core first:
  macOS:              brew install ansible
  Debian/Ubuntu:      sudo apt install ansible-core    (or: pipx install ansible-core)
  Anywhere (pipx):    pipx install --include-deps ansible"
fi
command -v openssl >/dev/null 2>&1 || die "openssl is required but not installed."

# --- 1. Ask the six questions ---------------------------------------------------
echo "A few questions (defaults in [brackets] — press Enter to accept):"
VPS_IP=$(ask "VPS IP or hostname (the fresh Ubuntu 24.04 server)")
SSH_USER=$(ask "SSH user for the FIRST bootstrap (root on most fresh VPS)" "root")
BASE_DOMAIN=$(ask "Base domain (A records for app/ci/grafana subdomains will be used)" "")
LE_EMAIL=$(ask "Email for Let's Encrypt (expiry notices)" "admin@${BASE_DOMAIN}")
APP_SUB=$(ask "App subdomain" "app")
CI_SUB=$(ask "CI subdomain (empty = skip CI subdomain)" "ci")
GRAF_SUB=$(ask "Grafana subdomain (empty = skip Grafana subdomain)" "grafana")
REPO_URL=$(ask "Git repo URL for the first image build" "https://github.com/your-org/go-template.git")
echo
if ! ask_yn "Deploy CI (Woodpecker) and monitoring (Prometheus/Grafana) on this VPS? Recommended for >= 4GB RAM"; then
  CI_ENABLED=false; MONITORING_ENABLED=false
else
  CI_ENABLED=true; MONITORING_ENABLED=true
fi
echo

APP_DOMAIN="${APP_SUB}.${BASE_DOMAIN}"
CI_DOMAIN="${CI_SUB:+${CI_SUB}.${BASE_DOMAIN}}"
GRAF_DOMAIN="${GRAF_SUB:+${GRAF_SUB}.${BASE_DOMAIN}}"

info "Generating secrets and encrypted vault"
mkdir -p "$STATE_DIR" "$(dirname "$SECRETS_FILE")"
umask 077
if [ ! -f "$VAULT_PASS" ]; then
  openssl rand -base64 32 > "$VAULT_PASS"
  chmod 600 "$VAULT_PASS"
fi

PG_PASS=$(openssl rand -hex 24)
JWT_SECRET=$(openssl rand -hex 32)
WP_SECRET=$(openssl rand -hex 24)
GRAF_PASS=$(openssl rand -base64 18 | tr -d '/+=' | head -c 24)

cat > "$SECRETS_FILE" <<EOF
# Generated by vps-setup on $(date -u +%Y-%m-%dT%H:%M:%SZ). Encrypted at rest.
secrets:
  postgres_password: "${PG_PASS}"
  jwt_secret: "${JWT_SECRET}"
  grafana_admin_password: "${GRAF_PASS}"
  woodpecker_agent_secret: "${WP_SECRET}"
  woodpecker_github_client_id: ""
  woodpecker_github_client_secret: ""
  telegram_bot_token: ""
  telegram_chat_id: ""
  slack_webhook_url: ""
  alerting_smtp_host: ""
  alerting_smtp_port: "587"
  alerting_smtp_from: ""
  alerting_smtp_to: ""
  alerting_smtp_username: ""
  alerting_smtp_password: ""
  app_smtp_password: ""
  app_oauth_google:   { client_id: "", client_secret: "" }
  app_oauth_github:   { client_id: "", client_secret: "" }
  app_oauth_facebook: { client_id: "", client_secret: "" }
  app_oauth_twitter:  { client_id: "", client_secret: "" }
  backup_rclone_remote: ""
  backup_rclone_config: ""
EOF
ansible-vault encrypt "$SECRETS_FILE" >/dev/null 2>&1 \
  || die "ansible-vault encrypt failed (is ansible installed?)"
ok "secrets.yml generated and encrypted (vault pass: ${VAULT_PASS})"

info "Writing site variables and inventory"
cat > "$SITE_VARS" <<EOF
# Machine-specific values written by vps-setup on $(date -u +%Y-%m-%dT%H:%M:%SZ).
# Overrides the defaults in main.yml (same directory, loaded after it).
app_domain: ${APP_DOMAIN}
ci_domain: ${CI_DOMAIN}
grafana_domain: ${GRAF_DOMAIN}
acme_email: ${LE_EMAIL}
ci_enabled: ${CI_ENABLED}
monitoring_enabled: ${MONITORING_ENABLED}
bootstrap_repo_url: ${REPO_URL}
EOF

cat > "$ANSIBLE_DIR/inventories/$VPS_SITE/hosts.yml" <<EOF
# Generated by vps-setup. After the first deploy hardens SSH, the working
# ansible_user switches to "deploy" automatically (see scripts/lib.sh).
all:
  children:
    vps:
      hosts:
        go-template-vps:
          ansible_host: ${VPS_IP}
          ansible_user: ${SSH_USER}
EOF

cat > "$STATE_FILE" <<EOF
vps_host="${VPS_IP}"
vps_ssh_user="${SSH_USER}"
EOF
ok "inventory + site vars written"

echo
info "Site '${VPS_SITE}' is ready. Next steps:"
echo "  1. Point DNS A records at ${VPS_IP}:"
echo "       ${APP_DOMAIN}"
[ -n "$CI_DOMAIN" ] && echo "       ${CI_DOMAIN}"
[ -n "$GRAF_DOMAIN" ] && echo "       ${GRAF_DOMAIN}"
echo "  2. make vps-doctor    # verifies ansible, SSH, DNS, VPS size"
echo "  3. make vps-deploy    # the one command — full stack, ~10-20 min"
